"""Keep PenguinOS Coral's generic system packages without GSI-only ownership checks.

Upstream `generic_system.mk` is intended to build a standalone GSI. Its
`require-artifacts-in-path-relaxed` claims `/system` for that *one* product.
The full Coral ROM legitimately adds its own system modules, system properties,
and framework matrices, so inheriting the GSI product triggers Soong errors.

Create a Coral-local copy of the *synced* generic_system.mk with ONLY that
require-artifacts call omitted, then switch the Coral product to inherit it.
This does not edit build/make or remove/relocate any runtime components.
"""
from pathlib import Path

GENERIC = Path("build/make/target/product/generic_system.mk")
CORAL_PRODUCT = Path("device/google/coral/aospa_coral.mk")
LOCAL_GENERIC = Path("device/google/coral/penguinos_system.mk")
UPSTREAM_INHERIT = "$(call inherit-product, $(SRC_TARGET_DIR)/product/generic_system.mk)"
CORAL_INHERIT = "$(call inherit-product, device/google/coral/penguinos_system.mk)"
OWNERSHIP = "$(call require-artifacts-in-path-relaxed, $(_my_paths), $(_my_allowed_list))"
HEADER = ("# Auto-generated by .repo/local_manifests/tools/coral_system.py\n"
          "# Retains upstream generic_system.mk modules and settings, but not its GSI-only\n"
          "# /system artifact ownership restriction. DO NOT EDIT MANUALLY.\n\n")


def prepare_coral_system(root: Path) -> list[Path]:
    root = Path(root)
    source_file = root / GENERIC
    product_file = root / CORAL_PRODUCT
    generated_file = root / LOCAL_GENERIC
    if not source_file.is_file() or not product_file.is_file():
        raise FileNotFoundError(
            "Coral product or build/make generic_system.mk missing; complete repo sync first"
        )

    upstream = source_file.read_text(encoding="utf-8")
    product = product_file.read_text(encoding="utf-8")
    # Refuse unexpected upstream changes: never silently strip other checks.
    if upstream.count(OWNERSHIP) != 1:
        raise ValueError("Unexpected generic_system.mk artifact requirement; refusing patch")
    if upstream.count("$(call require-artifacts-in-path") != 1:
        raise ValueError("Multiple generic_system.mk artifact constraints; refusing patch")

    original_count = product.count(UPSTREAM_INHERIT)
    modified_count = product.count(CORAL_INHERIT)
    if (original_count, modified_count) not in ((1, 0), (0, 1)):
        raise ValueError("Unexpected Coral product inheritance; refusing patch")

    # This is the ONLY semantic difference to the generic source product.
    generated = HEADER + upstream.replace(
        OWNERSHIP,
        "# Coral full-ROM build: intentionally omit the GSI-only /system ownership check.",
        1,
    )
    updated_product = product.replace(UPSTREAM_INHERIT, CORAL_INHERIT, 1)

    # Both input files are validated before either output is written.
    changes = []
    if modified_count == 0:
        product_file.write_text(updated_product, encoding="utf-8")
        changes.append(product_file)
    if not generated_file.is_file() or generated_file.read_text(encoding="utf-8") != generated:
        generated_file.write_text(generated, encoding="utf-8")
        changes.append(generated_file)
    if changes:
        print("PenguinOS Coral: preserved generic system packages without GSI ownership checks")
    else:
        print("PenguinOS Coral: generic system artifact configuration already prepared")
    return changes
